/**
 * LOBBY ADVANCES — how wide each character of the Lobby's three faces is,
 * measured from the app's own font files, as tables the app does arithmetic with.
 *
 *   node mockups/tools/lobby-advances.cjs
 *
 * Writes src/components/lobby/faceAdvances.ts. The Lobby decides, by these
 * widths, whether a line of its own words fits the room it is given at the
 * member's text size — and when it does not, the layout gives way (two bills
 * stand one above the other, a banner's door drops under its words) rather than
 * a line wrapping, being cut, or shrinking below the size it was set at. A
 * character count cannot tell a W from an I; these can.
 *
 * Every printable character of ASCII and Latin-1: the house's own words, and
 * the film titles and names the Lobby sizes. Anything else (Arabic, CJK…) is
 * measured as the face's widest letter, so an unknown letter never fits where
 * it would not.
 */
const fs = require('fs');
const path = require('path');
const { chromium, fonts } = require('./harness.cjs');

const CHARS = [
  ...Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => String.fromCharCode(0x20 + i)),
  ...Array.from({ length: 0xff - 0xa1 + 1 }, (_, i) => String.fromCharCode(0xa1 + i)),
  '’', '‘', '“', '”', '—', '–', '…', '·', '✦', '›', '★', '№',
];

// [the name in the table, the CSS font the harness loads]
const FACES = [
  ['RYE', "400 1000px 'Rye'"],
  ['ELITE', "400 1000px 'Special Elite'"],
  ['COURIER_ITALIC', "italic 400 1000px 'Courier Prime'"],
  ['SPECTRAL_ITALIC', "italic 400 1000px 'Spectral'"],
];

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(`<!doctype html><html><head><style>${fonts()}</style></head><body>
    <span style="font-family:Rye">A</span><span style="font-family:'Special Elite'">A</span>
    <span style="font-family:'Courier Prime';font-style:italic">A</span><span style="font-family:Spectral;font-style:italic">A</span>
  </body></html>`);
  await page.evaluate(() => document.fonts.ready);
  const tables = await page.evaluate(({ chars, faces }) => {
    const c = document.createElement('canvas').getContext('2d');
    const out = {};
    for (const [name, font] of faces) {
      c.font = font;
      const t = {};
      for (const ch of chars) t[ch] = Math.round(c.measureText(ch).width) / 1000;
      out[name] = t;
    }
    return out;
  }, { chars: CHARS, faces: FACES });
  await browser.close();

  const block = (name, table) => {
    const widest = Math.max(...Object.values(table));
    const rows = Object.entries(table).map(([ch, w]) => `  ${JSON.stringify(ch)}: ${w},`).join('\n');
    return `export const ${name}: Readonly<Record<string, number>> = {\n${rows}\n};\n/** A letter the table does not hold is measured as the widest it does. */\nexport const ${name}_WIDEST = ${widest};\n`;
  };
  const out = `/**
 * GENERATED by mockups/tools/lobby-advances.cjs from the app's own font files —
 * do not edit by hand; run the tool. Each value is a character's advance in ems.
 */
${FACES.map(([name]) => block(name, tables[name])).join('\n')}`;
  const dest = path.join(__dirname, '..', '..', 'src', 'components', 'lobby', 'faceAdvances.ts');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, out);
  console.log('wrote', path.relative(process.cwd(), dest), Object.fromEntries(FACES.map(([n]) => [n, Object.keys(tables[n]).length])));
})().catch((e) => { console.error(e); process.exit(1); });
